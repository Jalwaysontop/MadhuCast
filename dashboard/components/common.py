# --------------------------------------------------------------------------- session


def mode_key() -> str:
    return json.dumps(backend.describe(), sort_keys=True)


def init_session() -> None:
    ss = st.session_state
    if "now" not in ss:
        try:
            _, _, default_now = backend.time_window()
        except ContractError:
            default_now = datetime.now(ts.IST)
        ss.now = default_now
    if "pid" not in ss:
        try:
            pids = backend.list_patients()
        except ContractError:
            pids = []
        demo_pid = "P-010"
        ss.pid = demo_pid if (DEMO or demo_pid in pids) and demo_pid in pids else (pids[0] if pids else None)
    ss.setdefault("saved_scenarios", [])
    ss.setdefault("whatif_meal", None)


def open_patient(p: str) -> None:
    """Select a patient from inside a page; the sidebar applies it on the next run."""
    st.session_state._pid_pending = p
    st.session_state.pid = p


def now() -> datetime:
    return st.session_state.now


def pid() -> str | None:
    return st.session_state.pid


def load_css() -> None:
    """Inject the Jamun stylesheet for the active theme and register the Plotly templates."""
    plotly_template.register()
    st.markdown(f"<style>{css.stylesheet(kit.mode())}</style>", unsafe_allow_html=True)
    with st.container(key="theme-sync"):
        components.html(css.THEME_SYNC_JS, height=0)


def theme() -> Mode:
    return kit.mode()


# --------------------------------------------------------------------------- cached backend


@st.cache_data(show_spinner=False, max_entries=512)
def _state(p: str, now_iso: str, mode: str) -> PatientState:
    return backend.get_state(p, datetime.fromisoformat(now_iso))


@st.cache_data(show_spinner=False, max_entries=512)
def _run(p: str, now_iso: str, scenario_json: str, mode: str, explain: bool) -> tuple[PatientState, Forecast]:
    state = backend.get_state(p, datetime.fromisoformat(now_iso))
    return backend.run_scenario(state, Scenario.model_validate_json(scenario_json), explain=explain)


@st.cache_data(show_spinner="Replaying the day through the alert engine…")
def _replay(mode: str, step_min: int) -> list[al.Snapshot]:
    start, end, _ = backend.time_window()
    times, t = [], start
    while t <= end:
        times.append(t)
        t += timedelta(minutes=step_min)
    thr, _ = backend.thresholds()
    return al.replay(
        times, backend.list_patients(), backend.get_state, lambda s: backend.predict(s, explain=False), thr
    )


@st.cache_data(show_spinner=False)
def _report(name: str, mode: str) -> tuple[Any, str]:
    return backend.load_report(name)


@st.cache_data(show_spinner=False)
def _food_db(mode: str):
    return backend.food_db()


@st.cache_data(show_spinner=False)
def _patients(mode: str) -> list[str]:
    return backend.list_patients()


def get_state(p: str | None = None, at: datetime | None = None) -> PatientState:
    return _state(p or pid(), (at or now()).isoformat(), mode_key())


def run(
    p: str | None = None, at: datetime | None = None, scenario: Scenario | None = None, explain: bool = True
) -> tuple[PatientState, Forecast]:
    sc = (scenario or Scenario()).model_dump_json()
    return _run(p or pid(), (at or now()).isoformat(), sc, mode_key(), explain)


def snapshot(at: datetime | None = None, step_min: int = 15) -> al.Snapshot | None:
    snaps = _replay(mode_key(), step_min)
    at = at or now()
    past = [s for s in snaps if s.now <= at]
    return past[-1] if past else None


def snapshots_until(at: datetime | None = None, step_min: int = 15) -> list[al.Snapshot]:
    at = at or now()
    return [s for s in _replay(mode_key(), step_min) if s.now <= at]


def report(name: str) -> tuple[Any, str]:
    return _report(name, mode_key())


def food_db():
    return _food_db(mode_key())


def patients() -> list[str]:
    return _patients(mode_key())


def thresholds() -> tuple[dict, bool]:
    payload, label = report("thresholds")
    if payload is None:
        from src.serving.mock_predict import mock_thresholds

        return mock_thresholds(), False
    return payload, bool(payload.get("calibrated", label == "MODEL_ESTIMATE"))


def patient_alerts(state: PatientState, fc: Forecast) -> list[al.Candidate]:
    thr, _ = thresholds()
    return al.evaluate(al.AlertInput.from_state(state, fc), thr)


# --------------------------------------------------------------------------- badges (delegate to the kit)


def prov_badge(p: Provenance | str) -> str:
    return kit.provenance_badge(p.value if isinstance(p, Provenance) else str(p))


def tier_badge(tier: al.Tier, unknown: bool = False) -> str:
    return kit.tier_badge("UNKNOWN" if unknown else TIER_NAME[tier])


def md(html_str: str) -> None:
    kit.md(html_str)


def risk_level(state: PatientState, fc: Forecast) -> tuple[str, str]:
    """(label, tier) for the header pill. Stale data → 'Risk unknown', never low."""
    cands = patient_alerts(state, fc)
    if any(c.event == "unknown" for c in cands):
        return "Risk unknown", "UNKNOWN"
    top = max((c.tier for c in cands), default=al.Tier.NONE)
    return {
        al.Tier.CRITICAL: ("Critical risk", "CRITICAL"),
        al.Tier.WARNING: ("High risk", "WARNING"),
        al.Tier.WATCH: ("Elevated risk", "WATCH"),
        al.Tier.NONE: ("Low risk", "CLEAR"),
    }[top]


def dq_label(dq: float | None) -> tuple[str, str]:
    """(text, tier) for data quality."""
    if dq is None:
        return "unknown", "UNKNOWN"
    if dq >= 0.9:
        return f"OK, {dq:.0%}", "CLEAR"
    if dq >= 0.6:
        return f"Degraded, {dq:.0%}", "WATCH"
    return f"Poor, {dq:.0%}", "WARNING"


def backend_text() -> str:
    b = backend.describe()
    return (
        b["data"].capitalize() if b["data"] == b["model"] else f"data {b['data'].lower()}, model {b['model'].lower()}"
    )


# --------------------------------------------------------------------------- chrome


def error_card(e: Exception) -> None:
    """Errors state what happened and how to fix it. They never apologise."""
    if isinstance(e, ContractError):
        fix = (
            "Check the teammate's output against src/contracts.py, or switch that subsystem back to mock "
            "(MADHUTWIN_DATA=mock or MADHUTWIN_MODEL=mock) to preview."
        )
        st.error(
            f"**{e.source} does not match the contract, so this view is held back.** {fix}\n\n"
            f"```\n{e.detail[:1200]}\n```",
            icon=":material/report:",
        )
    else:
        st.error(f"**This view could not render:** {e}", icon=":material/report:")


def guard(fn: Callable[[], None]) -> None:
    """Run a page body; contract violations become a visible error card, never a silent failure."""
    try:
        fn()
    except ContractError as e:
        error_card(e)


def sidebar() -> None:
    init_session()
    logo = ASSETS / "logo.svg"
    if logo.exists():
        st.logo(str(logo), icon_image=str(ASSETS / "mark.svg"), size="large")
    with st.sidebar:
        try:
            pids = patients()
        except ContractError as e:
            error_card(e)
            return
        if pids:
            labels = [_patient_label(p) for p in pids]
            pending = st.session_state.pop("_pid_pending", None)
            if pending in pids:
                st.session_state.pid = pending
                st.session_state.pid_select = labels[pids.index(pending)]
            idx = pids.index(pid()) if pid() in pids else 0
            if st.session_state.get("pid_select") not in labels:
                st.session_state.pid_select = labels[idx]
            choice = st.selectbox("Patient", labels, key="pid_select")
            st.session_state.pid = pids[labels.index(choice)]
        try:
            start, end, _ = backend.time_window()
        except ContractError as e:
            error_card(e)
            return
        opts, t = [], start
        while t <= end:
            opts.append(t)
            t += timedelta(minutes=15)
        same_day = len({o.astimezone(ts.IST).date() for o in opts}) == 1
        fmt = "%H:%M" if same_day else "%a %H:%M"
        tlabels = [o.astimezone(ts.IST).strftime(fmt) for o in opts]
        cur = min(range(len(opts)), key=lambda i: abs((opts[i] - now()).total_seconds()))
        if st.session_state.get("now_slider") not in tlabels:
            st.session_state.now_slider = tlabels[cur]
        chosen = st.select_slider(
            "Replay time",
            options=tlabels,
            key="now_slider",
            help="Scrubs 'now' for every page. Times are IST (Asia/Kolkata).",
        )
        st.session_state.now = opts[tlabels.index(chosen)]
        if DEMO:
            kit.caption("Demo mode: seed, patient and replay time are pinned so the video is reproducible.")
        kit.md(
            f'<div class="mt-caption" style="margin-top:8px">Backend &nbsp;'
            f"{kit.provenance_badge(_data_badge())} data &nbsp;"
            f"{_model_badges()}</div>"
        )


def _data_badge() -> str:
    try:
        return backend.data_provenance()
    except ContractError:
        return "REAL"


def _model_badges() -> str:
    """One badge per forecast part, so a hybrid model (real spike classifier, mock curve) is never
    shown as wholly real."""
    try:
        parts = backend.model_parts()
    except ContractError:
        parts = {"model": "MODEL_ESTIMATE"}
    if len(parts) == 1:
        return f"{kit.provenance_badge(next(iter(parts.values())))} model"
    return " &nbsp;".join(f"{kit.provenance_badge(v)} {kit.esc(k)}" for k, v in parts.items())


def spike_source(fc: Forecast) -> str:
    """Foot note for a spike-probability readout when it and the curve come from different models."""
    if backend.is_real_spike(fc) and "MOCK" in backend.model_parts().values():
        return "XGBoost classifier; curve and hypo are MOCK"
    if "real model skipped" in (fc.model_version or ""):
        return "MOCK: real model skipped, under 6 h of fresh history"
    return ""


def _patient_label(p: str) -> str:
    try:
        st_ = get_state(p)
        return f"{p}  {st_.profile.cohort.upper() if st_.profile.cohort == 't2d' else st_.profile.cohort.capitalize()}, {st_.profile.age} {st_.profile.sex}"
    except Exception:
        return p


def header() -> None:
    if pid() is None:
        return
    try:
        state, fc = run()
    except ContractError as e:
        error_card(e)
        return
    cohort = {"t2d": "Type 2 diabetes", "prediabetes": "Prediabetes", "healthy": "No diabetes"}[state.profile.cohort]
    kit.header_bar(
        state.profile.patient_id,
        cohort,
        risk_level(state, fc),
        state.data_quality,
        state.uplink_mode,
        backend_text(),
        ts.hhmm(state.now),
    )


def footer() -> None:
    st.divider()
    kit.footer()


def disclaimer() -> None:
    kit.disclaimer(WHATIF_DISCLAIMER)
