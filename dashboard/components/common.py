ASSETS = Path(__file__).resolve().parents[1] / "assets"
DEMO = os.environ.get("MADHUTWIN_DEMO") == "1"
DISCLAIMER_FOOTER = "Synthetic/open data only. Research PoC, not a medical device."
WHATIF_DISCLAIMER = ("Model estimate learned from observational data, not a proven causal effect. "
                     "Not medical advice. Medication changes are intentionally excluded from what-if.")

TIER_STYLE = {  # icon + text, never colour alone
    al.Tier.CRITICAL: ("‼", "CRITICAL", "tier-critical"),
    al.Tier.WARNING: ("▲", "WARNING", "tier-warning"),
    al.Tier.WATCH: ("●", "WATCH", "tier-watch"),
    al.Tier.NONE: ("✓", "NO ALERT", "tier-none"),
}
PROV_HELP = {
    "REAL": "Measured data from an open dataset",
    "SYNTHETIC": "Simulated (e.g. Synthea EHR, synthetic genetic risk score, Indian meal augmentation)",
    "MOCK": "Placeholder generated by this repo until teammates' real outputs land",
    "MODEL_ESTIMATE": "Output of the model, with uncertainty; not a measurement",
}


# --------------------------------------------------------------------------- session


def mode_key() -> str:
    return json.dumps(backend.describe(), sort_keys=True)


def init_session() -> None:
    ss = st.session_state
    if "now" not in ss:
        try:
            _, _, default_now = backend.time_window()
        except ContractError:
            default_now = datetime.now(ts.IST)
        ss.now = default_now
    if "pid" not in ss:
        try:
            pids = backend.list_patients()
        except ContractError:
            pids = []
        demo_pid = "P-010"
        ss.pid = demo_pid if (DEMO or demo_pid in pids) and demo_pid in pids else (pids[0] if pids else None)
    ss.setdefault("saved_scenarios", [])
    ss.setdefault("whatif_meal", None)


def open_patient(p: str) -> None:
    """Select a patient from inside a page; the sidebar applies it on the next run."""
    st.session_state._pid_pending = p
    st.session_state.pid = p


def now() -> datetime:
    return st.session_state.now


def pid() -> str | None:
    return st.session_state.pid


def load_css() -> None:
    css = ASSETS / "style.css"
    if css.exists():
        st.markdown(f"<style>{css.read_text()}</style>", unsafe_allow_html=True)


# --------------------------------------------------------------------------- cached backend


@st.cache_data(show_spinner=False, max_entries=512)
def _state(p: str, now_iso: str, mode: str) -> PatientState:
    return backend.get_state(p, datetime.fromisoformat(now_iso))


@st.cache_data(show_spinner=False, max_entries=512)
def _run(p: str, now_iso: str, scenario_json: str, mode: str, explain: bool) -> tuple[PatientState, Forecast]:
    state = backend.get_state(p, datetime.fromisoformat(now_iso))
    return backend.run_scenario(state, Scenario.model_validate_json(scenario_json), explain=explain)


@st.cache_data(show_spinner="Replaying the day through the alert engine…")
def _replay(mode: str, step_min: int) -> list[al.Snapshot]:
    start, end, _ = backend.time_window()
    times, t = [], start
    while t <= end:
        times.append(t)
        t += timedelta(minutes=step_min)
    thr, _ = backend.thresholds()
    return al.replay(times, backend.list_patients(), backend.get_state,
                     lambda s: backend.predict(s, explain=False), thr)


@st.cache_data(show_spinner=False)
def _report(name: str, mode: str) -> tuple[Any, str]:
    return backend.load_report(name)


@st.cache_data(show_spinner=False)
def _food_db(mode: str):
    return backend.food_db()


@st.cache_data(show_spinner=False)
def _patients(mode: str) -> list[str]:
    return backend.list_patients()


def get_state(p: str | None = None, at: datetime | None = None) -> PatientState:
    return _state(p or pid(), (at or now()).isoformat(), mode_key())


def run(p: str | None = None, at: datetime | None = None, scenario: Scenario | None = None,
        explain: bool = True) -> tuple[PatientState, Forecast]:
    sc = (scenario or Scenario()).model_dump_json()
    return _run(p or pid(), (at or now()).isoformat(), sc, mode_key(), explain)


def snapshot(at: datetime | None = None, step_min: int = 15) -> al.Snapshot | None:
    snaps = _replay(mode_key(), step_min)
    at = at or now()
    past = [s for s in snaps if s.now <= at]
    return past[-1] if past else None


def report(name: str) -> tuple[Any, str]:
    return _report(name, mode_key())


def food_db():
    return _food_db(mode_key())


def patients() -> list[str]:
    return _patients(mode_key())


def thresholds() -> tuple[dict, bool]:
    payload, label = report("thresholds")
    if payload is None:
        from src.serving.mock_predict import mock_thresholds

        return mock_thresholds(), False
    return payload, bool(payload.get("calibrated", label == "MODEL_ESTIMATE"))


def patient_alerts(state: PatientState, fc: Forecast) -> list[al.Candidate]:
    thr, _ = thresholds()
    return al.evaluate(al.AlertInput.from_state(state, fc), thr)


# --------------------------------------------------------------------------- badges


def badge(text: str, cls: str, title: str = "") -> str:
    return f'<span class="mt-badge {cls}" title="{html.escape(title)}">{html.escape(text)}</span>'


def prov_badge(p: Provenance | str) -> str:
    v = p.value if isinstance(p, Provenance) else str(p)
    label = "MODEL ESTIMATE" if v == "MODEL_ESTIMATE" else v
    return badge(label, f"prov-{v.lower().replace('_', '-')}", PROV_HELP.get(v, ""))


def tier_badge(tier: al.Tier, unknown: bool = False) -> str:
    if unknown:
        return badge("? UNKNOWN", "tier-unknown", "Data missing or stale: risk cannot be assessed")
    icon, text, cls = TIER_STYLE[tier]
    return badge(f"{icon} {text}", cls)


def md(html_str: str) -> None:
    st.markdown(html_str, unsafe_allow_html=True)


def risk_level(state: PatientState, fc: Forecast) -> tuple[str, str]:
    """(label, css class) for the header. Stale data → UNKNOWN, never LOW."""
    cands = patient_alerts(state, fc)
    if any(c.event == "unknown" for c in cands):
        return "UNKNOWN", "tier-unknown"
    top = max((c.tier for c in cands), default=al.Tier.NONE)
    return {al.Tier.CRITICAL: ("CRITICAL", "tier-critical"), al.Tier.WARNING: ("HIGH", "tier-warning"),
            al.Tier.WATCH: ("ELEVATED", "tier-watch"), al.Tier.NONE: ("LOW", "tier-none")}[top]


def dq_label(dq: float | None) -> tuple[str, str]:
    if dq is None:
        return "UNKNOWN", "tier-unknown"
    if dq >= 0.9:
        return f"OK ({dq:.0%})", "tier-none"
    if dq >= 0.6:
        return f"DEGRADED ({dq:.0%})", "tier-watch"
    return f"POOR ({dq:.0%})", "tier-warning"


# --------------------------------------------------------------------------- chrome


def error_card(e: Exception) -> None:
    if isinstance(e, ContractError):
        st.error(f"**Contract error from {e.source}.** A teammate's output did not match `src/contracts.py`, so "
                 f"this view is not shown rather than shown wrong.\n\n```\n{e.detail[:1500]}\n```", icon="🚫")
    else:
        st.error(f"**Could not render this view:** {e}", icon="🚫")


def guard(fn: Callable[[], None]) -> None:
    """Run a page body; contract violations become a visible error card, never a silent failure."""
    try:
        fn()
    except ContractError as e:
        error_card(e)


def sidebar() -> None:
    init_session()
    with st.sidebar:
        st.markdown("### MadhuTwin")
        st.caption("T2D digital twin · research PoC")
        try:
            pids = patients()
        except ContractError as e:
            error_card(e)
            return
        if pids:
            labels = [_patient_label(p) for p in pids]
            pending = st.session_state.pop("_pid_pending", None)
            if pending in pids:
                st.session_state.pid = pending
                st.session_state.pid_select = labels[pids.index(pending)]
            idx = pids.index(pid()) if pid() in pids else 0
            if st.session_state.get("pid_select") not in labels:
                st.session_state.pid_select = labels[idx]
            choice = st.selectbox("Patient", labels, key="pid_select")
            st.session_state.pid = pids[labels.index(choice)]
        try:
            start, end, _ = backend.time_window()
        except ContractError as e:
            error_card(e)
            return
        opts, t = [], start
        while t <= end:
            opts.append(t)
            t += timedelta(minutes=15)
        same_day = len({o.astimezone(ts.IST).date() for o in opts}) == 1
        fmt = "%H:%M" if same_day else "%a %H:%M"
        tlabels = [o.astimezone(ts.IST).strftime(fmt) for o in opts]
        cur = min(range(len(opts)), key=lambda i: abs((opts[i] - now()).total_seconds()))
        if st.session_state.get("now_slider") not in tlabels:
            st.session_state.now_slider = tlabels[cur]
        chosen = st.select_slider("Replay time (scrubs 'now' for every page)", options=tlabels, key="now_slider")
        st.session_state.now = opts[tlabels.index(chosen)]
        if DEMO:
            st.info("Demo mode: seed, patient and replay time pinned for a reproducible video.", icon="🎬")
        st.divider()
        b = backend.describe()
        st.caption(f"Backend · data **{b['data']}** · model **{b['model']}**")
        st.caption("Times shown in IST (Asia/Kolkata).")


def _patient_label(p: str) -> str:
    try:
        st_ = get_state(p)
        return f"{p} · {st_.profile.cohort.upper()} · {st_.profile.age}{st_.profile.sex}"
    except Exception:
        return p


def header() -> None:
    if pid() is None:
        return
    try:
        state, fc = run()
    except ContractError as e:
        error_card(e)
        return
    risk, rcls = risk_level(state, fc)
    dq, dcls = dq_label(state.data_quality)
    b = backend.describe()
    backend_txt = b["data"] if b["data"] == b["model"] else f"data {b['data']} / model {b['model']}"
    md('<div class="mt-header">'
       f'<span class="mt-h-item"><b>Patient</b> {html.escape(state.profile.patient_id)}</span>'
       f'<span class="mt-h-item"><b>Risk</b> {badge(risk, rcls)}</span>'
       f'<span class="mt-h-item"><b>Data quality</b> {badge(dq, dcls)}</span>'
       f'<span class="mt-h-item"><b>Mode</b> {html.escape(state.uplink_mode or "n/a")}</span>'
       f'<span class="mt-h-item"><b>Backend</b> {html.escape(backend_txt)}</span>'
       f'<span class="mt-h-item mt-h-time"><b>Now</b> {ts.hhmm(state.now)} IST</span>'
       "</div>")


def footer() -> None:
    st.divider()
    legend = " ".join(prov_badge(p) for p in ("REAL", "SYNTHETIC", "MOCK", "MODEL_ESTIMATE"))
    md(f'<div class="mt-footer">Provenance: {legend}<br><b>{DISCLAIMER_FOOTER}</b> '
       "Model estimates are learned from observational data and are not causal effects.</div>")


def disclaimer() -> None:
    st.warning(WHATIF_DISCLAIMER, icon="⚠️")
